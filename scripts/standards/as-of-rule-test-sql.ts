// Builds scripts/sql/tests/test_standards_as_of_rule.sql from the shared synthetic case table
// tests/fixtures/fidrec-update/as-of-rule-cases.json (Lane 6's contract fixture; review of 24 Nov 2026, Decision 6),
// so the database functions run every case the fake provider runs. A contract test checks the committed file is what
// this builds; change the table, then run:
//
//   npx tsx scripts/standards/as-of-rule-test-sql.ts
//
// Synthetic data only; the SQL rolls everything back.

import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import type { AsOfRuleCase } from "../../supabase/functions/_shared/facts/update/contract.ts"
import { sqlLiteral } from "./sql.ts"

export const AS_OF_RULE_CASES_PATH = "tests/fixtures/fidrec-update/as-of-rule-cases.json"
export const AS_OF_RULE_TEST_SQL_PATH = "scripts/sql/tests/test_standards_as_of_rule.sql"

/** The named test Elena asks for at merge (lanes review, Decision 6; coordinator, 24 Nov). */
export const EUPG_LATER_START_TEST =
  "an EUPG paragraph starting on 16 June 2025 never prints for an earlier payment"

export function readAsOfRuleCases(path = AS_OF_RULE_CASES_PATH): AsOfRuleCase[] {
  return (JSON.parse(readFileSync(path, "utf8")) as { cases: AsOfRuleCase[] }).cases
}

function date(value: string | null): string {
  return value === null ? "NULL::date" : `${sqlLiteral(value)}::date`
}

export function buildAsOfRuleTestSql(cases: AsOfRuleCase[]): string {
  const documents = new Map<string, { rule: string; date: string; clauses: Map<string, string | null> }>()
  for (const c of cases) {
    const d = documents.get(c.documentKey) ?? { rule: c.asOfRule, date: c.documentDate, clauses: new Map() }
    if (d.rule !== c.asOfRule || d.date !== c.documentDate) {
      throw new Error(`${c.id}: ${c.documentKey} has another as-of rule or date in an earlier case`)
    }
    const start = d.clauses.get(c.clauseKey)
    if (start !== undefined && start !== c.clauseStart) throw new Error(`${c.id}: ${c.clauseKey} has another start`)
    d.clauses.set(c.clauseKey, c.clauseStart)
    documents.set(c.documentKey, d)
  }

  const load = [...documents].map(([key, d], i) => {
    const level = d.rule === "any_date" ? "announcement" : "guideline"
    const clauses = [...d.clauses].map(([clause, start]) =>
      `    (v_version, ${sqlLiteral(clause)}, ${sqlLiteral(`Synthetic text of ${clause}.`)}, '', ${date(start)})`).join(",\n")
    return `  -- ${key}: ${d.rule}, version dated ${d.date}
  INSERT INTO public.standard_documents (document_key, title, publisher, binding_level, applies_to, instrument_scope, as_of_rule)
  VALUES (${sqlLiteral(key)}, 'Synthetic document ${i + 1}', 'Synthetic publisher', '${level}', '{bank}', '{account_transfer,sg_card}', '${d.rule}')
  RETURNING id INTO v_document;
  INSERT INTO public.standard_document_versions (document_id, version_label, effective_from, provenance)
  VALUES (v_document, 'v1', ${date(d.date)}, 'publisher_site') RETURNING id INTO v_version;
  INSERT INTO public.standard_clauses (version_id, clause_key, text_content, text_sha256, effective_from_override) VALUES
${clauses};
  UPDATE public.standard_document_versions
  SET status = 'verified', source_url = 'https://example.test/${key}.pdf', snapshot_path = 'synthetic/${key}.pdf',
      content_sha256 = c_sha, retrieved_at = now(), verified_by = 'synthetic reviewer', verified_at = now()
  WHERE id = v_version;`
  }).join("\n\n")

  const checks = cases.map((c) => `  -- ${c.id}: ${c.standsFor}
  SELECT outcome, read_on INTO v_outcome, v_read_on
  FROM public.read_clause_under_as_of_rule_v1(${sqlLiteral(c.clauseKey)}, ${date(c.eventDate)}, ${date(c.generatedOn)});
  IF v_outcome IS DISTINCT FROM ${sqlLiteral(c.expected)}
     OR v_read_on IS DISTINCT FROM ${date(c.asOfRule === "any_date" ? c.generatedOn : c.eventDate)} THEN
    RAISE EXCEPTION 'as-of case ${c.id}: expected ${c.expected}, got % (read on %)', v_outcome, v_read_on;
  END IF;`).join("\n\n")

  const eupg = cases.find((c) => c.asOfRule === "event_date" && c.clauseStart !== null && c.expected === "held")
  const reply = cases.find((c) => c.asOfRule === "any_date" && c.expected === "held_after_the_events")
  if (!eupg || !reply) throw new Error("the case table needs a later-start event_date clause and a later-dated reply")

  return `-- Tests for 20261204120000_standards_as_of_rule.sql. GENERATED by scripts/standards/as-of-rule-test-sql.ts from
-- ${AS_OF_RULE_CASES_PATH}; do not edit by hand. Synthetic data only; everything is rolled back.
-- Run after all migrations: psql -v ON_ERROR_STOP=1 -f ${AS_OF_RULE_TEST_SQL_PATH}
-- Covers: every case in the shared table through read_clause_under_as_of_rule_v1; ${EUPG_LATER_START_TEST}, for
-- clauses and for a statement resting on it; a statement resting only on a reply is read on the generation day; a
-- statement resting on a reply and a guideline is read on the event date; any_date only on an announcement; the
-- rule is fixed once a version is verified.

BEGIN;

DO $$
DECLARE
  c_sha constant text := repeat('d', 64);
  v_document uuid;
  v_version uuid;
  v_outcome text;
  v_read_on date;
  v_rule text;
  v_count integer;
BEGIN
${load}

${checks}

  -- ${EUPG_LATER_START_TEST}
  SELECT count(*) INTO v_count FROM public.read_clause_under_as_of_rule_v1(${sqlLiteral(eupg.clauseKey)}, ${date(eupg.clauseStart)} - 1, ${date(eupg.generatedOn)})
  WHERE outcome <> 'not_held';
  IF v_count <> 0 THEN RAISE EXCEPTION '${EUPG_LATER_START_TEST}: clause held the day before its start'; END IF;
  SELECT count(*) INTO v_count FROM public.get_clause_as_of_v1(${sqlLiteral(eupg.clauseKey)}, ${date(eupg.clauseStart)} - 1);
  IF v_count <> 0 THEN RAISE EXCEPTION '${EUPG_LATER_START_TEST}: get_clause_as_of_v1 returned it'; END IF;
  INSERT INTO public.definition_statements (statement_key, framework, applies_to_instrument, text, clause_keys, status, approved_by, approved_at, clauses_as_of)
  VALUES ('test.asof.later_start', 'eupg', '{sg_card}', 'Synthetic statement on a later-start paragraph.', ARRAY[${sqlLiteral(eupg.clauseKey)}], 'approved', 'synthetic reviewer', now(), ${date(eupg.clauseStart)});
  SELECT count(*) INTO v_count FROM public.get_statement_for_case_v1('test.asof.later_start', ${date(eupg.clauseStart)} - 1, ${date(eupg.generatedOn)});
  IF v_count <> 0 THEN RAISE EXCEPTION '${EUPG_LATER_START_TEST}: statement returned for an earlier event'; END IF;
  SELECT as_of_rule, read_on INTO v_rule, v_read_on FROM public.get_statement_for_case_v1('test.asof.later_start', ${date(eupg.clauseStart)}, ${date(eupg.generatedOn)});
  IF v_rule IS DISTINCT FROM 'event_date' OR v_read_on IS DISTINCT FROM ${date(eupg.clauseStart)} THEN
    RAISE EXCEPTION '${EUPG_LATER_START_TEST}: statement not read on the event date from the start (% %)', v_rule, v_read_on;
  END IF;

  -- A statement resting only on a reply is read on the day the pack is generated.
  INSERT INTO public.definition_statements (statement_key, framework, applies_to_instrument, text, clause_keys, status, approved_by, approved_at, clauses_as_of)
  VALUES ('test.asof.reply_only', 'mas_reply', '{sg_card}', 'Synthetic statement on a reply.', ARRAY[${sqlLiteral(reply.clauseKey)}], 'approved', 'synthetic reviewer', now(), ${date(reply.documentDate)});
  SELECT as_of_rule, read_on INTO v_rule, v_read_on FROM public.get_statement_for_case_v1('test.asof.reply_only', ${date(reply.eventDate)}, ${date(reply.generatedOn)});
  IF v_rule IS DISTINCT FROM 'any_date' OR v_read_on IS DISTINCT FROM ${date(reply.generatedOn)} THEN
    RAISE EXCEPTION 'reply-only statement: expected any_date read on ${reply.generatedOn}, got % %', v_rule, v_read_on;
  END IF;
  SELECT count(*) INTO v_count FROM public.get_statement_as_of_v1('test.asof.reply_only', ${date(reply.eventDate)});
  IF v_count <> 0 THEN RAISE EXCEPTION 'reply-only statement: the event-date read should not hold it'; END IF;

  -- A statement resting on a reply and on an event-date paragraph keeps the event date.
  INSERT INTO public.definition_statements (statement_key, framework, applies_to_instrument, text, clause_keys, status, approved_by, approved_at, clauses_as_of)
  VALUES ('test.asof.mixed', 'mas_reply', '{sg_card}', 'Synthetic statement on both.', ARRAY[${sqlLiteral(reply.clauseKey)}, ${sqlLiteral(eupg.clauseKey)}], 'approved', 'synthetic reviewer', now(), ${date(reply.generatedOn)});
  SELECT count(*) INTO v_count FROM public.get_statement_for_case_v1('test.asof.mixed', ${date(reply.eventDate)}, ${date(reply.generatedOn)});
  -- Read for an event on the generation day, both are in force, so the row shows which rule decided.
  SELECT as_of_rule INTO v_rule FROM public.get_statement_for_case_v1('test.asof.mixed', ${date(reply.generatedOn)}, ${date(reply.generatedOn)});
  IF v_count <> 0 OR v_rule IS DISTINCT FROM 'event_date' THEN
    RAISE EXCEPTION 'mixed statement: expected the event date to decide (rows %, rule %)', v_count, v_rule;
  END IF;

  -- A document not held reads as event_date.
  IF public.get_document_as_of_rule_v1('test.not_held_document') <> 'event_date' THEN
    RAISE EXCEPTION 'a document not held should read as event_date';
  END IF;

  -- any_date only on an announcement.
  BEGIN
    INSERT INTO public.standard_documents (document_key, title, publisher, binding_level, as_of_rule)
    VALUES ('test.any_date_guideline', 'Synthetic', 'Synthetic', 'guideline', 'any_date');
    RAISE EXCEPTION 'any_date accepted on a guideline';
  EXCEPTION WHEN check_violation THEN NULL;
  END;

  -- The rule is fixed once a version is verified.
  BEGIN
    UPDATE public.standard_documents SET as_of_rule = 'event_date' WHERE document_key = ${sqlLiteral(reply.documentKey)};
    RAISE EXCEPTION 'as_of_rule changed on a document with a verified version';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
END;
$$;

SELECT 'standards as-of rule: all checks passed (${cases.length} cases)' AS result;

ROLLBACK;
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(AS_OF_RULE_TEST_SQL_PATH, buildAsOfRuleTestSql(readAsOfRuleCases()))
  console.log(`wrote ${AS_OF_RULE_TEST_SQL_PATH}`)
}
