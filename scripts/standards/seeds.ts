// The corpus seeds that are not documents: institutions, statement drafts, and the server rules' citations. Pure
// functions (read the seed files, build SQL); scripts/standards/seed.ts runs them.

import { readdirSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { FIDREC_CLAUSE_KEYS } from "../../supabase/functions/_shared/facts/rules/fidrec.ts"
import { SRF_CLAUSE_KEYS } from "../../supabase/functions/_shared/facts/rules/srf.ts"
import { readManifest } from "./manifest.ts"
import { sqlLiteral, sqlTextArray } from "./sql.ts"

export const MANIFEST_DIR = "supabase/standards/manifests"
export const INSTITUTIONS_FILE = "supabase/standards/seeds/institutions.json"
export const STATEMENTS_DIR = "supabase/standards/seeds/statements"

export interface SeedInstitution {
  code: string
  name: string
  type: string
  aliases: string[]
}

export interface SeedStatement {
  statement_key: string
  revision: number
  framework: string
  applies_to_instrument: string[]
  text: string
  clause_keys: string[]
  exclusion_clause_keys: string[]
  note?: string
}

export interface RuleCitation {
  rule_id: string
  clause_key: string
  source_file: string
}

export function readInstitutions(path = INSTITUTIONS_FILE): SeedInstitution[] {
  return (JSON.parse(readFileSync(path, "utf8")) as { institutions: SeedInstitution[] }).institutions
}

export function readStatements(dir = STATEMENTS_DIR): Array<SeedStatement & { file: string }> {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .flatMap((file) =>
      (JSON.parse(readFileSync(join(dir, file), "utf8")) as { statements: SeedStatement[] }).statements.map((s) => ({ ...s, file }))
    )
}

/** Every clause held by a committed manifest, with the scope it is loaded with (null: the document's). */
export function manifestClauses(dir = MANIFEST_DIR): Map<string, { scope: string[] }> {
  const out = new Map<string, { scope: string[] }>()
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    const m = readManifest(join(dir, file))
    for (const c of m.clauses) out.set(c.clause_key, { scope: c.instrument_scope ?? m.document.instrument_scope })
  }
  return out
}

function snake(name: string): string {
  return name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`)
}

/** standard_rule_citations rows, built from the clause keys in the rules' code. */
export function ruleCitations(): RuleCitation[] {
  const rows: RuleCitation[] = []
  for (const [code, keys] of Object.entries(SRF_CLAUSE_KEYS)) {
    for (const key of keys) rows.push({ rule_id: `srf.${code}`, clause_key: key, source_file: "supabase/functions/_shared/facts/rules/srf.ts" })
  }
  for (const [name, keys] of Object.entries(FIDREC_CLAUSE_KEYS)) {
    for (const key of keys) rows.push({ rule_id: `fidrec.${snake(name)}`, clause_key: key, source_file: "supabase/functions/_shared/facts/rules/fidrec.ts" })
  }
  return rows.sort((a, b) => (a.rule_id + a.clause_key < b.rule_id + b.clause_key ? -1 : 1))
}

/** The rule_id prefixes this build step owns; rows under them that the code no longer cites are removed. */
export const RULE_PREFIXES = ["srf.", "fidrec."]

const STATEMENT_COLUMNS = "framework, applies_to_instrument, text, clause_keys, exclusion_clause_keys"

export function buildSeedSql(input: {
  institutions: SeedInstitution[]
  statements: SeedStatement[]
  citations: RuleCitation[]
}): string {
  const inst = input.institutions.map((i) => `  (${sqlLiteral(i.code)}, ${sqlLiteral(i.name)}, ${sqlTextArray(i.aliases)})`)
  const stmts = input.statements.map((s) => `  (${[
    sqlLiteral(s.statement_key), String(s.revision), sqlLiteral(s.framework), sqlTextArray(s.applies_to_instrument),
    sqlLiteral(s.text), sqlTextArray(s.clause_keys), sqlTextArray(s.exclusion_clause_keys),
  ].join(", ")})`)
  const cites = input.citations.map((c) => `  (${sqlLiteral(c.rule_id)}, ${sqlLiteral(c.clause_key)}, ${sqlLiteral(c.source_file)})`)
  const prefixes = sqlTextArray(RULE_PREFIXES.map((p) => `${p}%`))

  return `-- Generated by scripts/standards/seed.ts. Institutions, statement drafts and rule citations; a second run changes
-- nothing. Statements are written as drafts only; an approved or retired revision is never changed.
\\set ON_ERROR_STOP on
BEGIN;

CREATE TEMP TABLE _seed_institutions (code text PRIMARY KEY, name text NOT NULL, aliases text[] NOT NULL) ON COMMIT DROP;
CREATE TEMP TABLE _seed_statements (
  statement_key text NOT NULL, revision integer NOT NULL, framework text NOT NULL, applies_to_instrument text[] NOT NULL,
  text text NOT NULL, clause_keys text[] NOT NULL, exclusion_clause_keys text[] NOT NULL,
  PRIMARY KEY (statement_key, revision)
) ON COMMIT DROP;
CREATE TEMP TABLE _seed_citations (rule_id text, clause_key text, source_file text, PRIMARY KEY (rule_id, clause_key)) ON COMMIT DROP;
${inst.length ? `INSERT INTO _seed_institutions VALUES\n${inst.join(",\n")};` : ""}
${stmts.length ? `INSERT INTO _seed_statements VALUES\n${stmts.join(",\n")};` : ""}
${cites.length ? `INSERT INTO _seed_citations VALUES\n${cites.join(",\n")};` : ""}

DO $seed$
DECLARE
  v_n integer;
  v_inst integer := 0;
  v_stmt integer := 0;
  v_cite integer := 0;
  v_bad text;
BEGIN
  INSERT INTO public.standard_institutions (code, name, aliases)
  SELECT code, name, aliases FROM _seed_institutions ORDER BY code
  ON CONFLICT (code) DO NOTHING;
  GET DIAGNOSTICS v_n = ROW_COUNT; v_inst := v_inst + v_n;
  UPDATE public.standard_institutions i SET name = s.name, aliases = s.aliases
  FROM _seed_institutions s WHERE i.code = s.code AND (i.name, i.aliases) IS DISTINCT FROM (s.name, s.aliases);
  GET DIAGNOSTICS v_n = ROW_COUNT; v_inst := v_inst + v_n;

  -- An approved or retired revision is fixed: a changed seed for it must be a new revision.
  SELECT string_agg(d.statement_key || ' r' || d.revision, ', ' ORDER BY d.statement_key) INTO v_bad
  FROM public.definition_statements d JOIN _seed_statements s USING (statement_key, revision)
  WHERE d.status <> 'draft'
    AND (d.${STATEMENT_COLUMNS.split(", ").join(", d.")}) IS DISTINCT FROM (s.${STATEMENT_COLUMNS.split(", ").join(", s.")});
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'standards_seed_statement_not_draft',
      DETAIL = 'Changed seed for a revision that is no longer a draft: ' || v_bad || '. Add a new revision instead.';
  END IF;
  INSERT INTO public.definition_statements (statement_key, revision, ${STATEMENT_COLUMNS})
  SELECT s.statement_key, s.revision, s.${STATEMENT_COLUMNS.split(", ").join(", s.")}
  FROM _seed_statements s
  WHERE NOT EXISTS (
    SELECT 1 FROM public.definition_statements d WHERE d.statement_key = s.statement_key AND d.revision = s.revision
  )
  ORDER BY s.statement_key, s.revision;
  GET DIAGNOSTICS v_n = ROW_COUNT; v_stmt := v_stmt + v_n;
  UPDATE public.definition_statements d SET (${STATEMENT_COLUMNS}) = (s.${STATEMENT_COLUMNS.split(", ").join(", s.")})
  FROM _seed_statements s
  WHERE d.statement_key = s.statement_key AND d.revision = s.revision AND d.status = 'draft'
    AND (d.${STATEMENT_COLUMNS.split(", ").join(", d.")}) IS DISTINCT FROM (s.${STATEMENT_COLUMNS.split(", ").join(", s.")});
  GET DIAGNOSTICS v_n = ROW_COUNT; v_stmt := v_stmt + v_n;

  INSERT INTO public.standard_rule_citations (rule_id, clause_key, source_file)
  SELECT rule_id, clause_key, source_file FROM _seed_citations ORDER BY rule_id, clause_key
  ON CONFLICT (rule_id, clause_key) DO NOTHING;
  GET DIAGNOSTICS v_n = ROW_COUNT; v_cite := v_cite + v_n;
  UPDATE public.standard_rule_citations r SET source_file = s.source_file
  FROM _seed_citations s WHERE r.rule_id = s.rule_id AND r.clause_key = s.clause_key AND r.source_file <> s.source_file;
  GET DIAGNOSTICS v_n = ROW_COUNT; v_cite := v_cite + v_n;
  DELETE FROM public.standard_rule_citations r
  WHERE r.rule_id LIKE ANY (${prefixes})
    AND NOT EXISTS (SELECT 1 FROM _seed_citations s WHERE s.rule_id = r.rule_id AND s.clause_key = r.clause_key);
  GET DIAGNOSTICS v_n = ROW_COUNT; v_cite := v_cite + v_n;

  RAISE NOTICE 'standards seed: institutions % changed, statements % changed (drafts), rule citations % changed',
    v_inst, v_stmt, v_cite;
END;
$seed$;

COMMIT;
`
}
