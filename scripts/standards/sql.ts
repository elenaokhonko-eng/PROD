// The SQL that loads one manifest into a database as a draft version. It never sets a version to verified or a
// statement to approved; that is a person's step. Running it again changes no row: every write is guarded by
// "not there yet" or "different from what is there". A version that is no longer a draft is only compared, and a
// difference stops the load.

import type { Manifest } from "./manifest.ts"
import type { CutClause } from "./segment.ts"

export function sqlLiteral(value: string | null): string {
  if (value === null) return "NULL"
  if (value.includes("\u0000")) throw new Error("text contains a NUL character")
  return `'${value.replace(/'/g, "''")}'`
}

export function sqlTextArray(values: string[] | null): string {
  if (values === null) return "NULL::text[]"
  if (!values.length) return "'{}'::text[]"
  return `ARRAY[${values.map(sqlLiteral).join(", ")}]::text[]`
}

function sqlDate(value: string | null): string {
  return value === null ? "NULL::date" : `${sqlLiteral(value)}::date`
}

/** `manifestRepoPath` is recorded as manifest_path on a selected-sections version. */
export function buildLoadSql(manifest: Manifest, cut: CutClause[], manifestRepoPath: string): string {
  const d = manifest.document
  const v = manifest.version
  const byKey = new Map(cut.map((c) => [c.clause_key, c]))
  const rows = manifest.clauses.map((c) => {
    const text = byKey.get(c.clause_key)
    if (!text) throw new Error(`${c.clause_key} was not cut`)
    return `  (${[
      sqlLiteral(c.clause_key),
      sqlLiteral(c.clause_ref),
      sqlTextArray(c.heading_path),
      sqlLiteral(text.text),
      sqlLiteral(c.text_sha256),
      sqlTextArray(c.tags),
      sqlDate(c.effective_from_override),
      sqlTextArray(c.instrument_scope),
    ].join(", ")})`
  })

  const docValues = [
    sqlLiteral(d.title), sqlLiteral(d.publisher), sqlLiteral(d.binding_level), sqlTextArray(d.applies_to),
    sqlTextArray(d.instrument_scope), sqlLiteral(d.institution), sqlLiteral(d.card_scheme), sqlLiteral(d.canonical_url),
  ].join(", ")
  const docColumns = "title, publisher, binding_level, applies_to, instrument_scope, institution, card_scheme, canonical_url"
  const versionValues = [
    sqlDate(v.effective_from), sqlDate(v.issued_on), `${sqlLiteral(v.retrieved_at)}::timestamptz`, sqlLiteral(v.source_url),
    sqlLiteral(v.snapshot_path), sqlLiteral(v.content_sha256), sqlLiteral(v.provenance), sqlLiteral(v.coverage),
    sqlLiteral(v.coverage === "selected_sections" ? manifestRepoPath : null),
  ].join(", ")
  const versionColumns =
    "effective_from, issued_on, retrieved_at, source_url, snapshot_path, content_sha256, provenance, coverage, manifest_path"
  const clauseColumns = "clause_ref, heading_path, text_content, tags, effective_from_override, instrument_scope"
  const key = sqlLiteral(d.document_key)
  const label = sqlLiteral(v.version_label)

  return `-- Generated by scripts/standards/load.ts from the manifest for ${d.document_key}, ${v.version_label}.
-- Loads a draft version only. Run with psql; a second run changes nothing.
\\set ON_ERROR_STOP on
BEGIN;

CREATE TEMP TABLE _standards_load (
  clause_key text PRIMARY KEY,
  clause_ref text,
  heading_path text[] NOT NULL,
  text_content text NOT NULL,
  text_sha256 text NOT NULL,
  tags text[] NOT NULL,
  effective_from_override date,
  instrument_scope text[]
) ON COMMIT DROP;

INSERT INTO _standards_load (clause_key, ${clauseColumns.replace("text_content, ", "text_content, text_sha256, ")}) VALUES
${rows.join(",\n")};

DO $load$
DECLARE
  v_document uuid;
  v_version uuid;
  v_status text;
  v_n integer;
  v_changed integer := 0;
  v_bad text;
BEGIN
  INSERT INTO public.standard_documents (document_key, ${docColumns})
  VALUES (${key}, ${docValues})
  ON CONFLICT (document_key) DO NOTHING;
  GET DIAGNOSTICS v_n = ROW_COUNT; v_changed := v_changed + v_n;
  UPDATE public.standard_documents SET (${docColumns}) = (${docValues})
  WHERE document_key = ${key} AND (${docColumns}) IS DISTINCT FROM (${docValues});
  GET DIAGNOSTICS v_n = ROW_COUNT; v_changed := v_changed + v_n;
  SELECT id INTO v_document FROM public.standard_documents WHERE document_key = ${key};

  SELECT id, status INTO v_version, v_status FROM public.standard_document_versions
  WHERE document_id = v_document AND version_label = ${label};

  IF v_version IS NULL THEN
    INSERT INTO public.standard_document_versions (document_id, version_label, ${versionColumns})
    VALUES (v_document, ${label}, ${versionValues})
    RETURNING id, status INTO v_version, v_status;
    v_changed := v_changed + 1;
  ELSIF v_status = 'draft' THEN
    UPDATE public.standard_document_versions SET (${versionColumns}) = (${versionValues})
    WHERE id = v_version AND (${versionColumns}) IS DISTINCT FROM (${versionValues});
    GET DIAGNOSTICS v_n = ROW_COUNT; v_changed := v_changed + v_n;
  ELSE
    -- Verified or withdrawn: its record and text are fixed. The manifest must describe it exactly.
    IF EXISTS (
      SELECT 1 FROM public.standard_document_versions
      WHERE id = v_version AND (${versionColumns}) IS DISTINCT FROM (${versionValues})
    ) THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'standards_loader_version_not_draft',
        DETAIL = 'The version is ' || v_status || ' and its record differs from the manifest; a correction is a new version.';
    END IF;
    SELECT string_agg(COALESCE(l.clause_key, c.clause_key), ', ' ORDER BY COALESCE(l.clause_key, c.clause_key)) INTO v_bad
    FROM _standards_load l
    FULL JOIN (SELECT * FROM public.standard_clauses WHERE version_id = v_version) c ON c.clause_key = l.clause_key
    WHERE l.clause_key IS NULL OR c.clause_key IS NULL
       OR (c.${clauseColumns.split(", ").join(", c.")}) IS DISTINCT FROM (l.${clauseColumns.split(", ").join(", l.")});
    IF v_bad IS NOT NULL THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'standards_loader_version_not_draft',
        DETAIL = 'The version is ' || v_status || ' and these clauses differ from the manifest: ' || v_bad;
    END IF;
  END IF;

  IF v_status = 'draft' THEN
    DELETE FROM public.standard_clauses c
    WHERE c.version_id = v_version AND NOT EXISTS (SELECT 1 FROM _standards_load l WHERE l.clause_key = c.clause_key);
    GET DIAGNOSTICS v_n = ROW_COUNT; v_changed := v_changed + v_n;

    -- A changed text drops its embedding: it was computed from the old text.
    UPDATE public.standard_clauses c
    SET (${clauseColumns}) = (l.${clauseColumns.split(", ").join(", l.")}),
        embedding = CASE WHEN c.text_content = l.text_content THEN c.embedding END,
        embedding_model = CASE WHEN c.text_content = l.text_content THEN c.embedding_model END
    FROM _standards_load l
    WHERE c.version_id = v_version AND c.clause_key = l.clause_key
      AND (c.${clauseColumns.split(", ").join(", c.")}) IS DISTINCT FROM (l.${clauseColumns.split(", ").join(", l.")});
    GET DIAGNOSTICS v_n = ROW_COUNT; v_changed := v_changed + v_n;

    INSERT INTO public.standard_clauses (version_id, clause_key, ${clauseColumns}, text_sha256)
    SELECT v_version, l.clause_key, l.${clauseColumns.split(", ").join(", l.")}, ''
    FROM _standards_load l
    WHERE NOT EXISTS (SELECT 1 FROM public.standard_clauses c WHERE c.version_id = v_version AND c.clause_key = l.clause_key)
    ORDER BY l.clause_key;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_changed := v_changed + v_n;
  END IF;

  -- The database computes each hash itself (standard_clauses_guard); it must be the manifest's.
  SELECT string_agg(l.clause_key, ', ' ORDER BY l.clause_key) INTO v_bad
  FROM _standards_load l
  LEFT JOIN public.standard_clauses c ON c.version_id = v_version AND c.clause_key = l.clause_key
  WHERE c.text_sha256 IS DISTINCT FROM l.text_sha256;
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'standards_loader_hash_mismatch', DETAIL = v_bad;
  END IF;

  RAISE NOTICE 'standards loader: % "%" (%): % row(s) changed, % clause(s)',
    ${key}, ${label}, v_status, v_changed, (SELECT count(*) FROM _standards_load);
END;
$load$;

COMMIT;
`
}

